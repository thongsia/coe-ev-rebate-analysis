    v["grade_bid_ev"] = g("rebate->demand (bidding channel)", "ev_era_2022plus")
    v["grade_reg"] = g("rebate->demand (registration channel)", "descriptive")
    v["grade_dp_full"] = g("demand->price", "full_window")
    v["grade_dp_ev"] = g("demand->price", "ev_era_2022plus")
    v["grade_med_full"] = g("total indirect effect (rebate->demand->price)", "full_window")
    v["grade_med_ev"] = g("total indirect effect (rebate->demand->price)", "ev_era_2022plus")

    # ---- EV descriptive ----
    ev = pd.read_csv(TABLES / "ev_registrations_descriptive.csv")
    s = ev[ev["month"].astype(str).str.startswith("SUMMARY_")].set_index("month")
    v["ev_n"] = float(s.loc["SUMMARY_observed_months", "ev_reg"])
    v["ev_mean"] = float(s.loc["SUMMARY_mean_ev_reg", "ev_reg"])
    v["ev_max"] = float(s.loc["SUMMARY_max_ev_reg", "ev_reg"])
    v["ev_min"] = float(s.loc["SUMMARY_min_ev_reg", "ev_reg"])
    v["ev_share_mean"] = float(s.loc["SUMMARY_mean_ev_share", "ev_reg"])
    v["ev_share_max"] = float(s.loc["SUMMARY_max_ev_share", "ev_reg"])
    v["ev_cum"] = float(s.loc["SUMMARY_cumulative_ev_reg", "ev_reg"])
    v["ev_cov_min"] = float(s.loc["SUMMARY_min_coverage", "ev_reg"])
    v["ev_cov_max"] = float(s.loc["SUMMARY_max_coverage", "ev_reg"])

    # ---- dose / audit ----
    ds = pd.read_csv(TABLES / "dose_summary.csv").set_index("item")
    v["dose_changes"] = int(ds.loc["effective_in_window_changes", "value"])
    v["dose_vals"] = str(ds.loc["distinct_dose_values", "value"])
    v["dose_n"] = int(ds.loc["n_distinct_dose_values", "value"])
    v["dose_2022plus_vals"] = str(ds.loc["dose_2022plus_values", "value"])
    v["dose_2022plus_n"] = int(ds.loc["n_distinct_dose_values_2022plus", "value"])
    v["est_windows"] = str(ds.loc["estimation_windows", "value"])
    da = pd.read_csv(TABLES / "data_audit.csv").set_index("metric")
    v["coe_rows"] = int(da.loc["fetched_rows_coe", "value"])
    v["reg_rows"] = int(da.loc["fetched_rows_registrations", "value"])
    v["cpi_rows"] = int(da.loc["fetched_rows_cpi", "value"])
    v["panel_rows"] = int(da.loc["panel_row_count", "value"])
    v["gap"] = str(da.loc["coe_exercise_gap", "value"])

    # ---- rebate timeline ----
    v["timeline"] = pd.read_csv(TABLES / "rebate_timeline.csv")

    # ---- checklist summary ----
    try:
        chk = pd.read_csv(TABLES / "report_figures_checklist.csv")
        v["chk_n"] = len(chk)
        v["chk_ok"] = int((chk["match"] == "OK").sum())
    except FileNotFoundError:
        v["chk_n"] = 0
        v["chk_ok"] = 0
    return v


