#!/usr/bin/env python3
"""
Step 16 (Batch C) — Final report generator (verified real policy).

Writes docs/REPORT.md + docs/STATS_SUMMARY.md (inside the repo's docs/ dir).

HARD RULE: every number quoted in the report is READ from a saved table
(tables/*.csv) at runtime — nothing is recomputed. The report is generated by
a template that pulls each value through ``G(table, {filter}, col)``; if a
value cannot be located in a table, the script FAILS (no silent fabrication).

DESIGN (verified real Singapore policy):
  * dose_nominal_sgd = combined max EV rebate available that month (S$,
    nominal): 20000 (2016-01..2017-12, CEVS ESTIMATE) / 25000 (VES A1,
    2018-01..2020-12) / 45000 (VES A1 + EEAI cap 20k, 2021-01..2023-12) /
    40000 (VES A1 + EEAI cap 15k, 2024-01..2025-05). 4 distinct in-window
    values. The 2016-01..2017-12 CEVS dose is an ESTIMATE (flagged).
  * REAL-POLICY dummies: reg_real_ves_201801 (VES onset), reg_real_evstack_202101
    (enhanced VES + EEAI stack), reg_arffloor_zero_202201 ($0 ARF floor — a
    TAX provision, not a rebate), reg_eeai_cap15k_202401 (EEAI cap cut 20k->15k).
  * DUAL SCOPE: the full window (2016-01..2025-05) is the PRIMARY estimation
    scope for the CEVS->VES transition + overall level effects; the 2022+ EV
    era (2022-01..2025-05, 41 obs, dose 45000 -> 40000 at 2024-01) is ALSO a
    VALID ESTIMATION scope for the headline price + bidding + mediation
    exhibits (the verified dose varies within it). Both scopes are reported for every causal exhibit, with the
    negative-control verdict per scope.
  * Collinearity: the continuous dose and the binary dummies are near-exact
    linear transforms of one another; no spec mixes both (dose-only OR
    dummy-only, per exhibit).

Layering contract:
  READS tables/*.csv, data/processed/*.csv (data dictionary only),
        tables/report_figures_checklist.csv (written by 14_verify.py)
  WRITES docs/REPORT.md, docs/STATS_SUMMARY.md
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "tables"
DOCS = ROOT / "docs"

_MISsING: list[str] = []


def G(table: str, flt: dict, col: str, row_key: str = ""):
    """Fetch a single value from a saved table; hard-fail if absent."""
    df = pd.read_csv(TABLES / table)
    m = df
    for k, v in flt.items():
        m = m[m[k].astype(str).str.strip() == str(v)]
    if len(m) == 0:
        _MISsING.append(f"{table} {flt} -> {col}")
        raise SystemExit(f"HARD-FAIL: value not found in {table} for {flt} ({col})")
    val = m[col].iloc[0]
    try:
        return float(val)
    except (TypeError, ValueError):
        return str(val)


def Gtxt(table: str, flt: dict, col: str) -> str:
    """Fetch a single text value; hard-fail if absent."""
    df = pd.read_csv(TABLES / table)
    m = df
    for k, v in flt.items():
        m = m[m[k].astype(str).str.strip() == str(v)]
    if len(m) == 0:
        _MISsING.append(f"{table} {flt} -> {col} (text)")
        raise SystemExit(f"HARD-FAIL: text not found in {table} for {flt} ({col})")
    return str(m[col].iloc[0])


def f0(x):  # noqa: D103
    return f"{x:,.0f}"


def f1(x):
    return f"{x:,.1f}"


def fp(x):  # p-value
    return f"{x:.3g}"


