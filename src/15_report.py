    v["ev_cum"] = float(s.loc["SUMMARY_cumulative_ev_reg", "ev_reg"])
    v["ev_cov_min"] = float(s.loc["SUMMARY_min_coverage", "ev_reg"])
    v["ev_cov_max"] = float(s.loc["SUMMARY_max_coverage", "ev_reg"])
