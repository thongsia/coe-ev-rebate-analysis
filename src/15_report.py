    for c in ("coef", "se", "t", "p", "ci_lo", "ci_hi", "coef_pct_of_mean"):
        nc[c] = pd.to_numeric(nc[c], errors="coerce")
    v["nc_2022"] = {r["category"]: r for _, r in
                    nc[(nc["scope"] == "full_window")
                       & (nc["term"] == "reg_arffloor_zero_202201")].iterrows()}
    v["nc_2024"] = {r["category"]: r for _, r in
                    nc[(nc["scope"] == "ev_era_2022plus")
                       & (nc["term"] == "reg_eeai_cap15k_202401")].iterrows()}
    # read the same-effect-on-clean flags directly from the comment rows
    _same = {}
    for _, r in nc_all.iterrows():
        t = str(r["term"]).strip()
        if t.startswith("# same_effect_on_clean_controls_"):
            _same[t.split("=")[0].strip()] = t.split("=")[1].strip()
    v["nc_2022_same"] = _same.get("# same_effect_on_clean_controls_2022", "n/a")
    v["nc_2024_same"] = _same.get("# same_effect_on_clean_controls_2024", "n/a")

    # ---- diagnostics ----
    dg = pd.read_csv(TABLES / "diagnostics_stationarity_autocorr.csv")
    v["dw"] = [str(r["note"]) for _, r in dg.iterrows()
               if str(r["note"]).startswith("Durbin-Watson")][0]
    v["lb1"] = dg[dg["note"].astype(str) == "Ljung-Box Q(1)"].iloc[0]
    v["adf_price_level"] = dg[(dg["variable"] == "catA_clearing_price (nominal)")
                              & (dg["form"] == "level")].iloc[0]
    v["adf_price_diff"] = dg[(dg["variable"] == "catA_clearing_price (nominal)")
                             & (dg["form"] == "1st diff")].iloc[0]
