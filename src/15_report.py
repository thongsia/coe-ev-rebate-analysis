        ("evstack", "reg_real_evstack_202101"),
        ("arffloor", "reg_arffloor_zero_202201"),
        ("cap15k", "reg_eeai_cap15k_202401"),
        ("d1", "demand_l1"),
        ("d2", "demand_l2"),
